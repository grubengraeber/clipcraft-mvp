export type Locale = "de" | "en";

export const locales: Locale[] = ["de", "en"];
export const DEFAULT_LOCALE: Locale = "de";
export const LOCALE_STORAGE_KEY = "clipcraft_locale";
export const LOCALE_HEADER = "x-clipcraft-locale";

export function resolveLocale(value: string | null | undefined): Locale {
  const normalized = String(value || "").toLowerCase();
  if (normalized.startsWith("en")) return "en";
  if (normalized.startsWith("de")) return "de";
  return DEFAULT_LOCALE;
}

export function getRequestLocale(request: Request): Locale {
  return resolveLocale(
    request.headers.get(LOCALE_HEADER) ?? request.headers.get("accept-language"),
  );
}

export function jsonHeaders(locale: Locale) {
  return {
    "Content-Type": "application/json",
    [LOCALE_HEADER]: locale,
  };
}

export function localeHeader(locale: Locale) {
  return {
    [LOCALE_HEADER]: locale,
  };
}

export function getMessages(locale: Locale) {
  return messages[locale];
}

export function planPriceLabel(label: string, locale: Locale) {
  if (locale === "en") {
    return label.replace(" / Monat", " / month");
  }
  return label;
}

